def lectures_for(school):
    return [lec for lec in LECTURES if school in lec["levels"]]


def get_lecture(lid):
    return next(lec for lec in LECTURES if lec["id"] == lid)


def make_quiz(lid, rng=random):
    return get_lecture(lid)["quiz"](rng)
