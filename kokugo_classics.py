def pick_by_tags(theme, items, rng):
    """テーマの言葉が tags に入っている作品を優先して1つえらぶ（なければ、どれか1つ）"""
    hits = [c for c in items if any(t in theme or theme in t for t in c["tags"])]
    return rng.choice(hits or items)
